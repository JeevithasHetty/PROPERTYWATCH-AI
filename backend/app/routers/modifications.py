import datetime
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session
from sqlalchemy import desc

from app.database import get_db
from app.models import Modification, Property, ImageAnalysis, AuditLog, User, Evidence, Review
from app.schemas import ModificationCreate, ModificationUpdate, ModificationOut, ModificationDetailOut
from app.auth import get_current_user, require_roles

router = APIRouter(prefix="/modifications", tags=["Modification Alerts"])

def generate_modification_alert_id(db: Session) -> str:
    """
    Generate unique collision-resistant modification alert ID: MOD-YYYY-XXXX.
    Database-backed atomic sequencing.
    """
    year = datetime.datetime.utcnow().year
    count = db.query(Modification).count()
    candidate = f"MOD-{year}-{count + 1:04d}"
    while db.query(Modification).filter(Modification.modification_alert_id == candidate).first():
        count += 1
        candidate = f"MOD-{year}-{count + 1:04d}"
    return candidate

@router.get("", response_model=List[ModificationOut])
def list_modification_alerts(
    property_id: Optional[int] = Query(None),
    status_filter: Optional[str] = Query(None, alias="status"),
    category: Optional[str] = Query(None),
    skip: int = 0,
    limit: int = 50,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """List modification alerts with filtering by property, status, or category."""
    query = db.query(Modification)
    if current_user.role == "owner":
        query = query.join(Property).filter(Property.owner_user_id == current_user.id)

    if property_id:
        query = query.filter(Modification.property_id == property_id)
    if status_filter:
        query = query.filter(Modification.status == status_filter)
    if category:
        query = query.filter(Modification.suspected_category == category)

    mods = query.order_by(desc(Modification.created_at)).offset(skip).limit(limit).all()

    results = []
    for m in mods:
        m_out = ModificationOut.model_validate(m)
        m_out.property_reference = m.property.property_reference if m.property else None
        m_out.property_address = m.property.address if m.property else None
        m_out.evidence_count = len(m.evidence_items)
        m_out.reviewer_name = m.reviewer.name if m.reviewer else None
        results.append(m_out)

    return results

@router.post("", response_model=ModificationOut, status_code=status.HTTP_201_CREATED)
def create_modification_alert(
    mod_in: ModificationCreate,
    db: Session = Depends(get_db),
    current_user: User = Depends(require_roles(["admin", "reviewer", "manager"]))
):
    """
    Generate a new Modification Alert from an Image Analysis or property inspection.
    Assigns a collision-resistant unique Alert ID (e.g. MOD-2026-0001).
    """
    prop = db.query(Property).filter(Property.id == mod_in.property_id).first()
    if not prop:
        raise HTTPException(status_code=404, detail="Property not found")
    if mod_in.analysis_id:
        analysis = db.query(ImageAnalysis).filter(ImageAnalysis.id == mod_in.analysis_id).first()
        if not analysis or analysis.property_id != prop.id:
            raise HTTPException(status_code=400, detail="The image analysis must belong to the selected property.")

    alert_id = generate_modification_alert_id(db)

    # If linked to an analysis, grab score if not explicitly given
    change_score = mod_in.change_score or 0.0
    if mod_in.analysis_id:
        analysis = db.query(ImageAnalysis).filter(ImageAnalysis.id == mod_in.analysis_id).first()
        if analysis and not mod_in.change_score:
            change_score = analysis.change_score

    modification = Modification(
        modification_alert_id=alert_id,
        property_id=prop.id,
        analysis_id=mod_in.analysis_id,
        suspected_category=mod_in.suspected_category,
        description=mod_in.description,
        status="New",
        change_score=change_score,
        detected_at=datetime.datetime.utcnow(),
        created_at=datetime.datetime.utcnow(),
        updated_at=datetime.datetime.utcnow()
    )
    db.add(modification)
    db.commit()
    db.refresh(modification)

    # Log audit
    audit = AuditLog(
        user_id=current_user.id,
        entity_type="Modification",
        entity_id=str(modification.id),
        action="MODIFICATION_ALERT_CREATED",
        new_state={
            "alert_id": alert_id,
            "property_reference": prop.property_reference,
            "category": modification.suspected_category,
            "change_score": modification.change_score
        },
        notes=f"Alert generated by {current_user.name} ({current_user.role})"
    )
    db.add(audit)
    db.commit()

    m_out = ModificationOut.model_validate(modification)
    m_out.property_reference = prop.property_reference
    m_out.property_address = prop.address
    return m_out

@router.get("/{modification_id}", response_model=ModificationDetailOut)
def get_modification_alert_detail(
    modification_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Retrieve complete modification dossier including analysis overlays, evidence, and review logs."""
    mod = db.query(Modification).filter(Modification.id == modification_id).first()
    if not mod:
        raise HTTPException(status_code=404, detail="Modification alert not found")
    if current_user.role == "owner" and mod.property.owner_user_id != current_user.id:
        raise HTTPException(status_code=403, detail="Access denied. You do not own this property's modification alert.")

    m_out = ModificationDetailOut.model_validate(mod)
    m_out.property_reference = mod.property.property_reference if mod.property else None
    m_out.property_address = mod.property.address if mod.property else None
    m_out.evidence_count = len(mod.evidence_items)
    m_out.reviewer_name = mod.reviewer.name if mod.reviewer else None
    return m_out

@router.put("/{modification_id}", response_model=ModificationOut)
def update_modification_alert(
    modification_id: int,
    mod_in: ModificationUpdate,
    db: Session = Depends(get_db),
    current_user: User = Depends(require_roles(["admin", "reviewer"]))
):
    """Update modification alert status, reviewer assignment, or category."""
    mod = db.query(Modification).filter(Modification.id == modification_id).first()
    if not mod:
        raise HTTPException(status_code=404, detail="Modification alert not found")

    prev_state = {"status": mod.status, "reviewer_id": mod.reviewer_id, "category": mod.suspected_category}

    update_data = mod_in.model_dump(exclude_unset=True)
    for field, val in update_data.items():
        setattr(mod, field, val)

    mod.updated_at = datetime.datetime.utcnow()
    db.commit()
    db.refresh(mod)

    # Log audit
    audit = AuditLog(
        user_id=current_user.id,
        entity_type="Modification",
        entity_id=str(mod.id),
        action="MODIFICATION_ALERT_UPDATED",
        previous_state=prev_state,
        new_state=update_data,
        notes=f"Updated by {current_user.name}"
    )
    db.add(audit)
    db.commit()

    m_out = ModificationOut.model_validate(mod)
    m_out.property_reference = mod.property.property_reference if mod.property else None
    m_out.property_address = mod.property.address if mod.property else None
    m_out.reviewer_name = mod.reviewer.name if mod.reviewer else None
    return m_out
